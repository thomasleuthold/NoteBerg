// src/components/overviewMode.test.js
// Covers searchAllNotes' glob matching, specifically its ReDoS fix. The
// original implementation translated glob queries ("*"/"?" wildcards) into a
// regex (escapeRegex(query).replace(/\*/g, ".*")) and ran .test() against
// note content — a run of adjacent ".*" groups against long non-matching
// text is catastrophic-backtracking regex. Confirmed empirically before
// fixing: a 3-wildcard query against 800 characters of non-matching content
// took 41 SECONDS (single-threaded JS, so this froze the whole app, not just
// search); 2 wildcards were already badly non-linear (2000 chars: 3.2s; 4000
// chars: 24s). A wildcard-count cap does not fix this, since 2 adjacent
// wildcards already suffice for exponential blowup — the real fix is the
// linear (non-regex) two-pointer glob scan now used by globQueryMatches/
// wildcardMatch, confirmed here to have no such blowup regardless of
// wildcard count or content length, while preserving the exact old matching
// semantics (case-insensitive, unanchored, "*" = any run of chars incl.
// none, "?" = exactly one char).
//
// This matters more via MCP (mcpBridge.js's search_notes tool) than via the
// UI search box, since a query there can be generated by an LLM rather than
// typed by a person.

import { beforeEach, describe, expect, it, vi } from "vitest";

