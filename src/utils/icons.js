/**
 * Create an icon element
 * @param {string} name - Icon name
 * @param {number} size - Icon size (default: 24)
 * @param {string} className - Additional CSS class
 * @returns {HTMLElement} Span element containing the icon
 */
export function createIcon(name, size = 24, className = "") {
  const span = document.createElement("span");
  span.className = `icon ${className}`.trim();
  span.innerHTML = getIcon(name, size);
  return span;
}
